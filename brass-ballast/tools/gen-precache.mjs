#!/usr/bin/env node
// Generates precache-manifest.js: the file list and content-hash version that sw.js precaches.
//
//   node brass-ballast/tools/gen-precache.mjs
//
// Included: index.html, manifest.webmanifest, and everything under css/, js/, icons/.
// Excluded (never listed): tests/, tools/, docs/, *.md, package.json, eslint.config.mjs, sw.js,
// precache-manifest.js, dotfiles. The version is the first 12 hex chars of a SHA-256 over every included path and
// its bytes, so any change to a shipped file yields a new cache name.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = path.join(GAME_ROOT, 'precache-manifest.js');

const ROOT_FILES = ['index.html', 'manifest.webmanifest'];
const ROOT_DIRS = ['css', 'js', 'icons'];
const EXCLUDED_NAMES = new Set(['precache-manifest.js', 'sw.js', 'eslint.config.mjs']);

/** Recursively list files under `dir` (relative to GAME_ROOT, forward slashes). */
function walk(dir) {
  const out = [];
  for (const ent of fs.readdirSync(path.join(GAME_ROOT, dir), { withFileTypes: true })) {
    if (ent.name.startsWith('.')) continue;
    const rel = `${dir}/${ent.name}`;
    if (ent.isDirectory()) out.push(...walk(rel));
    else if (ent.isFile()) out.push(rel);
  }
  return out;
}

function isIncluded(rel) {
  const base = rel.split('/').pop();
  if (base.startsWith('.') || base.endsWith('.md')) return false;
  if (EXCLUDED_NAMES.has(base)) return false;
  return true;
}

const files = [
  ...ROOT_FILES,
  ...ROOT_DIRS.flatMap((d) => walk(d)),
]
  .filter((rel) => fs.existsSync(path.join(GAME_ROOT, rel)))
  .filter(isIncluded)
  .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const hash = crypto.createHash('sha256');
let bytes = 0;
for (const rel of files) {
  const buf = fs.readFileSync(path.join(GAME_ROOT, rel));
  bytes += buf.length;
  hash.update(rel);
  hash.update('\0');
  hash.update(buf);
  hash.update('\0');
}
const version = hash.digest('hex').slice(0, 12);

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const list = ['./', ...files].map((f) => `    ${q(f)},`).join('\n');
const source = `// GENERATED by tools/gen-precache.mjs. Do not edit by hand.
self.PRECACHE = {
  version: ${q(version)},
  files: [
${list}
  ],
};
`;
fs.writeFileSync(OUT_FILE, source);

console.log(
  `precache: ${files.length + 1} entries (${files.length} files), ${bytes} bytes, version ${version}`
);
